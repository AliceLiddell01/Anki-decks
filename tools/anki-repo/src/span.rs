//! Координаты исходного текста HTML/CSS/media.
//!
//! Полуоткрытый диапазон байтов одного неизменённого буфера. Границы строковых
//! срезов должны лежать на границах UTF-8; координаты после замены не переиспользуются.
//! Это не диапазон элементов индекса, не iterator и не RangeBounds запроса.
//! Новый Range хранит координаты и копируется, не являясь изменяемым iterator.

pub type Span = core::range::Range<usize>;
